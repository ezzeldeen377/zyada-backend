<p>تعمل زيادة كمنصة تقنية وسيطة لإدراج المنتجات وتنسيق الطلبات والتحصيل المالي عبر مزود الدفع. وإلى الحد الأقصى الذي يجيزه القانون المعمول به، لا تتحمل زيادة أي أضرار غير مباشرة أو تبعية أو خسارة أرباح. وتقتصر المسؤولية الإجمالية لزيادة الناشئة عن هذه الاتفاقية في كافة الأحوال على إجمالي مبالغ العمولات التي استلمتها فعلياً من التاجر خلال الأشهر الثلاثة السابقة على الواقعة محل المطالبة.</p>

<div class="section-title">15. مطالبات الغير والتعويض (Indemnification)</div>
<p>يلتزم التاجر بتعويض منصة زيادة ومديريها وموظفيها عن أي مطالبات أو خسائر أو غرامات أو أتعاب قانونية تنشأ عن إخلال التاجر بالتزاماته أو سلامة منتجاته أو مخالفته للقوانين والأنظمة المعمول بها في الدولة أو التعدي على حقوق الملكية الفكرية للغير.</p>

<div class="section-title">16. القانون الواجب التطبيق والاختصاص القضائي</div>
<p>تخضع هذه الاتفاقية وتفسر وفقاً للقوانين والتشريعات الاتحادية المعمول بها في دولة الإمارات العربية المتحدة والقوانين المحلية لإمارة دبي. ويخضع أي نزاع ينشأ عن هذه الاتفاقية أو يرتبط بها للاختصاص القضائي الحصري لمحاكم دبي المختصة، ما لم يتفق الطرفان صراحةً على خلاف ذلك كتابةً.</p>

<div class="section-title">17. أحكام عامة</div>
<p>تشكل هذه الاتفاقية مجمل التفاهم والاتفاق بين الطرفين فيما يتعلق بموضوعها وتلغي كافة المناقشات والتفاهمات السابقة. ولا يعتد بأي تعديل عليها إلا إذا تم كتابةً وبموافقة الطرفين. وإذا تبين بطلان أي بند من بنود هذه الاتفاقية، فإن ذلك لا يؤثر على صحة ونفاذ باقي البنود. وتعتبر التواقيع والموافقات والنسخ المتبادلة إلكترونياً بمثابة النسخ الأصلية ولها كامل الحجية القانونية في الإثبات وفقاً لقانون المعاملات الإلكترونية وخدمات الثقة الإماراتي.</p>

<div class="section-title">18. وثائق التسجيل والتحقق الإلزامية</div>
<p>كشرط تعاقدي أساسي للتسجيل والتفعيل على منصة زيادة، يلتزم التاجر برفع نسخ واضحة وسارية المفعول من المستندات التالية عبر المنظومة الآمنة المخصصة داخل التطبيق، ويؤكد ممثله المفوض صحتها وصلاحيته في تمثيل المنشأة، وتستخدم للتحقق من هوية التاجر وأهليته ومعلومات التسوية المصرفية:</p>
<ul>
    <li><strong>الرخصة التجارية:</strong> متضمنة كافة الصفحات وتصاريح الأنشطة والفروع المطلوبة.</li>
    <li><strong>بطاقة الهوية الإماراتية وجواز السفر:</strong> لمالك المنشأة أو المفوض بالتوقيع والشركاء والمستفيدين الحقيقيين بحسب متطلبات التحقق القانوني، مصحوبة بوثيقة التفويض أو ما يثبت صلاحية التوقيع عند الاقتضاء.</li>
    <li><strong>شهادة الحساب البنكي الرسمية (شهادة الآيبان):</strong> خطاب بنكي مختوم يثبت حساب المستفيد ويوضح اسم البنك، واسم صاحب الحساب، ورقم الحساب، والآيبان (IBAN)، والفرع. وتظل هذه البيانات في ملف التحقق الآمن خارج صلب هذه الاتفاقية.</li>
    <li><strong>شهادة التسجيل في ضريبة القيمة المضافة (VAT Certificate):</strong> في حال كانت المنشأة مسجلة ضريبياً، وبيانات المستفيد الحقيقي وفقاً للأنظمة السارية.</li>
</ul>

<div class="section-title">19. الإخطارات واستقلالية الأطراف</div>
<p>تُوجه كافة الإخطارات والمراسلات إلى البريد الإلكتروني وبيانات الاتصال المسجلة في حساب التاجر وقنوات التواصل الرسمية لزيادة داخل التطبيق، مع الاحتفاظ بما يثبت الإرسال. ويلتزم كل طرف بإخطار الآخر بأي تغيير يطرأ على بياناته. ولا تنشئ هذه الاتفاقية أي علاقة شراكة فعلية، أو علاقة عمل، أو وكالة تجارية مسجلة، أو حصرية بين الطرفين، ولا يملك أي طرف سلطة إلزام الطرف الآخر خارج النطاق المصرح به صراحةً، ويتحمل كل طرف نفقات أعماله الخاصة.</p>

<div class="section-title">20. القبول الإلكتروني وسجل الشروط</div>
